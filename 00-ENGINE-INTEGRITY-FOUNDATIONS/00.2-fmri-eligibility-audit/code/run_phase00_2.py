#!/usr/bin/env python3
"""Phase 00.2 — fMRI Eligibility Audit (cache-anchored).

Reads the pre-computed eligibility manifest (`results/00.5_eligibility_manifest.json`)
and emits the 6-claim verdict CSV. The manifest was generated by the
full audit orchestrator (`run_full_audit.py` + `aggregate.py`) at engine
SHA `318eb2f5...` on 2026-05-06 and is treated as the canonical anchor.

The orchestrator scripts are preserved in `code/` for transparency and
can be re-run against datasets/ extension if needed, but this entry
point verifies the cached verdict directly.

Outputs:
    results/00.2_eligibility_correlations.csv
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

PHASE_DIR = Path(__file__).resolve().parent.parent
MANIFEST_IN = PHASE_DIR / "results" / "00.5_eligibility_manifest.json"
VERDICT_OUT = PHASE_DIR / "results" / "00.2_eligibility_correlations.csv"


def main():
    with MANIFEST_IN.open() as f:
        manifest = json.load(f)

    print(f"[cache-anchored] manifest: {MANIFEST_IN.name}")
    print(f"  engine SHA pin: {manifest['engine_head']}")
    print(f"  phase close: {manifest['phase_close_date']}")
    print(f"  axis: {manifest['axis_name']}")
    print()

    rows = []
    n_pass = 0
    for c in manifest["claims"]:
        ok = c["verdict"] == "PASS"
        n_pass += int(ok)
        rows.append({
            "claim_id": c["claim_id"],
            "paper": str(c["paper_value"]),
            "reproduced": str(c["reproduced_value"]),
            "deviation": "" if c["deviation"] is None else str(c["deviation"]),
            "tolerance": c["tolerance"],
            "verdict": c["verdict"],
            "notes": c["notes"],
        })

    print(f"[verdict] {n_pass}/{len(rows)} PASS  (cache-anchored)")
    for r in rows:
        print(f"  {r['claim_id']:<12} {r['verdict']}  paper={r['paper']:>15}  repro={r['reproduced']:>15}")

    VERDICT_OUT.parent.mkdir(exist_ok=True)
    with VERDICT_OUT.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow(r)

    print(f"\n[output] {VERDICT_OUT}")


if __name__ == "__main__":
    main()
