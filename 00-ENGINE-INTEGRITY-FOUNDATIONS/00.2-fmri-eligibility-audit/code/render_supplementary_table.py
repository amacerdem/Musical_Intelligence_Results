"""Render eligibility_audit.csv into paper-ready Supplementary Table LaTeX.

Output: paper-evidence/Supplementary_Table_S-Eligibility.tex
"""
from __future__ import annotations

import csv
from pathlib import Path

PHASE_DIR = Path(__file__).resolve().parent.parent
CSV_IN = PHASE_DIR / "results" / "eligibility_audit.csv"
TEX_OUT = PHASE_DIR / "paper-evidence" / "Supplementary_Table_S-Eligibility.tex"


def latex_escape(s: str) -> str:
    """Escape LaTeX-sensitive chars in plain text."""
    s = str(s)
    repl = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
        "<": r"\textless{}",
        ">": r"\textgreater{}",
    }
    for k, v in repl.items():
        s = s.replace(k, v)
    return s


def render_short(value: str) -> str:
    """Compact verdict tokens for table cells."""
    return value.replace("yes_in_dataset", "yes-in").replace(
        "yes_external_DOI", "yes-DOI"
    ).replace("summary_only", "summary").replace(
        "no_recoverable", "no"
    ).replace("events_tsv_sub_TR", "sub-TR").replace(
        "events_tsv_TR_only", "TR-only"
    ).replace("recoverable_from_logs", "logs").replace(
        "none_recoverable", "none"
    ).replace("not_applicable", "n/a").replace(
        "runnable_via_fmriprep", "runnable"
    ).replace("not_feasible", "infeasible")


def main() -> None:
    rows = list(csv.DictReader(CSV_IN.open()))

    n_total = len(rows)
    n_compat = sum(1 for r in rows if r["mi_compatible"] == "True")

    lines = [
        "% Supplementary Table S-Eligibility — V-fMRI dataset eligibility audit",
        "% Generated by 00-ENGINE-INTEGRITY-FOUNDATIONS/00.2-fmri-eligibility-audit/code/render_supplementary_table.py",
        "% DO NOT EDIT BY HAND — re-render via the script.",
        r"\begingroup",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.05}",
        r"\begin{table}[!ht]",
        r"\centering",
        r"\scriptsize",
        rf"\caption{{V-fMRI dataset eligibility audit. {n_total} datasets audited; {n_compat} satisfy MI-compatibility (audio + sub-TR onsets + MNI-derivative-feasible + $\geq 1$ alignment-qualified subject). The remaining {n_total - n_compat} are excluded with documented reason. Phase consumer column links each dataset to its downstream V-Reproduction phase. Pre-registered 2026-05-06.}}",
        r"\label{tab:s-eligibility}",
        r"\begin{tabular}{l l r l l l r r c l}",
        r"\toprule",
        r"Dataset & Mod. & $N_{ds}$ & Audio & Timing & MNI & $N_{QC}$ & $N_{align}$ & MI-cmp. & Phase \\",
        r"\midrule",
    ]

    for r in rows:
        ds = latex_escape(r["dataset_id"])
        mod = latex_escape(r["modality"])
        n_ds = r["n_dataset_level"]
        audio = latex_escape(render_short(r["audio_available"]))
        timing = latex_escape(render_short(r["exact_timing"]))
        mni = latex_escape(render_short(r["mni_derivative"]))
        n_qc = r["n_qc_pass"]
        n_al = r["n_alignment_qualified"]
        compat = r"\textbf{Y}" if r["mi_compatible"] == "True" else "N"
        phase = latex_escape(r["phase_consumer"])
        lines.append(
            f"{ds} & {mod} & {n_ds} & {audio} & {timing} & {mni} & {n_qc} & {n_al} & {compat} & {phase} \\\\"
        )

    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        r"\endgroup",
        "",
        r"% Footnote summary:",
        rf"% Total: {n_total} datasets ({n_compat} MI-compatible / {n_total - n_compat} excluded)",
        r"% ds002725 alignment-qualified N = 17 (vs dataset-level N=21).",
        r"% ds003720 framed as routing-ablation, not population estimate.",
        r"% Phase 18 sub-axis verdicts: 18.1 ELIG, 18.2 NON-ELIG, 18.3 NON-ELIG, 18.4 NON-ELIG, 18.5 ELIG.",
    ])

    TEX_OUT.parent.mkdir(parents=True, exist_ok=True)
    TEX_OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {TEX_OUT} ({n_total} rows, {n_compat} MI-compatible)")


if __name__ == "__main__":
    main()
