#!/usr/bin/env python3
"""Phase 00.3 — Compute Profile (cache-anchored).

Reads the pre-computed manifest (`results/04_compute_profile_manifest.json`)
and emits the 6-claim verdict CSV. The manifest was generated by the
benchmark + latency + memory + determinism pipeline (run.sh) at engine
SHA `318eb2f5...` on 2026-05-06 (Apple M2 8GB, single-threaded).

Verdict breakdown:
  - 1/6 PASS (C-COMPUTE-06 determinism, bit-identical MD5 match)
  - 5/6 CAVEAT (C-COMPUTE-01..05, paper-disclosed hardware-tier mismatch;
    paper benchmarks were collected on M2 Max 64GB, this audit on M2 base
    8GB — bit-determinism reproduces verbatim, absolute timing/throughput
    track the hardware-class delta).

The CAVEAT verdicts are paper-disclosed and load-bearing only at the
hardware-tier disclosure level, not at the engine-correctness level.

Outputs:
    results/00.3_compute_profile_correlations.csv
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

PHASE_DIR = Path(__file__).resolve().parent.parent
MANIFEST_IN = PHASE_DIR / "results" / "04_compute_profile_manifest.json"
VERDICT_OUT = PHASE_DIR / "results" / "00.3_compute_profile_correlations.csv"


def main():
    with MANIFEST_IN.open() as f:
        manifest = json.load(f)

    print(f"[cache-anchored] manifest: {MANIFEST_IN.name}")
    print(f"  engine SHA pin: {manifest['engine_head']}")
    print(f"  phase close: {manifest['phase_close_date']}")
    print(f"  axis: {manifest['axis_name']}")
    print()

    rows = []
    counts = {"PASS": 0, "CAVEAT": 0, "FAIL": 0, "PARTIAL": 0}
    for c in manifest["claims"]:
        v = c["verdict"]
        counts[v] = counts.get(v, 0) + 1
        rows.append({
            "claim_id": c["claim_id"],
            "paper": str(c["paper_value"]),
            "reproduced": str(c["reproduced_value"]),
            "deviation": "" if c["deviation"] is None else str(c["deviation"]),
            "tolerance": c["tolerance"],
            "verdict": c["verdict"],
            "notes": c["notes"],
        })

    print(f"[verdict] PASS={counts['PASS']}  CAVEAT={counts['CAVEAT']}  FAIL={counts['FAIL']}")
    print()
    for r in rows:
        print(f"  {r['claim_id']:<15} {r['verdict']:<8} paper={r['paper'][:25]:<25}  repro={r['reproduced'][:25]}")

    VERDICT_OUT.parent.mkdir(exist_ok=True)
    with VERDICT_OUT.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow(r)

    print(f"\n[output] {VERDICT_OUT}")


if __name__ == "__main__":
    main()
